  var lang = 'uz';

  function t(key, params) {
    var s = DICT[lang][key];
    if (s == null) s = DICT.uz[key];
    if (s == null) return key;
    if (params) s = s.replace(/\{(\w+)\}/g, function (m, k) { return params[k] != null ? String(params[k]) : m; });
    return s;
  }

  function apply(root) {
    root = root || document;
    var each = function (sel, fn) { Array.prototype.forEach.call(root.querySelectorAll(sel), fn); };
    each('[data-i18n]', function (e) { e.textContent = t(e.getAttribute('data-i18n')); });
    each('[data-i18n-ph]', function (e) { e.placeholder = t(e.getAttribute('data-i18n-ph')); });
    each('[data-i18n-aria]', function (e) { e.setAttribute('aria-label', t(e.getAttribute('data-i18n-aria'))); });
    each('[data-i18n-title]', function (e) { e.title = t(e.getAttribute('data-i18n-title')); });
  }

  function setLang(l) {
    lang = LANGS.indexOf(l) !== -1 ? l : 'uz';
    document.documentElement.lang = lang;
    apply(document);
    document.title = t('meta.title');
    return lang;
  }

  /** Saqlangan til, bo'lmasa brauzer tili (rus/ingliz), aks holda o'zbekcha. */
  function detect(saved) {
    if (LANGS.indexOf(saved) !== -1) return saved;
    var list = navigator.languages || [navigator.language || ''];
    for (var i = 0; i < list.length; i++) {
      var code = String(list[i]).slice(0, 2).toLowerCase();
      if (code === 'uz') return 'uz';
      if (code === 'ru') return 'ru';
    }
    return 'uz';
  }

  window.I18N = {
    LANGS: LANGS,
    t: t,
    apply: apply,
    setLang: setLang,
    detect: detect,
    lang: function () { return lang; },
    cols: function () { return COLS[lang]; },
    coord: function (r, c) { return COLS[lang][c] + (r + 1); },
    dict: DICT
  };
